// Kapitel 3.1 – Was ist eine Variable?

// Eine Variable anlegen und ausgeben
let alter = 38;
console.log(alter);

console.log();

// Einen Namen nur an einer Stelle ändern
const vorname = "Lena";

console.log("Hallo,", vorname);
console.log(vorname, "ist heute dabei.");
console.log("Bis bald,", vorname);

console.log();

// Variablenname vs. Text
console.log(vorname);
console.log("vorname");

console.log();

// Mit Variablen rechnen
const stueckPreis = 4;
const anzahl = 3;
const gesamt = stueckPreis * anzahl;

console.log("Gesamtpreis:", gesamt);
