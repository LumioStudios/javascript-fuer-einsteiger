// Lösung zu Übung 3.1 – Dein Steckbrief mit Variablen

// Diese Werte ändern sich nicht
const vorname = "Lena";
const stadt = "Hamburg";
const lieblingsZahl = 7;
const trinktKaffee = true;

// Das Alter ändert sich jedes Jahr
let alter = 34;

console.log("Vorname:", vorname);
console.log("Stadt:", stadt);
console.log("Alter:", alter);
console.log("Lieblingszahl:", lieblingsZahl);
console.log("Trinkt gern Kaffee:", trinktKaffee);

// Ein Jahr später
alter = 35;
console.log("Neues Alter:", alter);
