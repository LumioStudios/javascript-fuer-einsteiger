// Kapitel 3.5 – Numbers (Zahlen)

const anzahlTage = 7;
const temperatur = -3;
const kontoStand = 1250.75;

console.log(anzahlTage);
console.log(temperatur);
console.log(kontoStand);

// Achtung: Komma trennt Werte
console.log(3,5);

console.log();

// Große Zahlen mit Unterstrichen
const einwohner = 83_000_000;
console.log(einwohner);

console.log();

// Rechnen mit Numbers
const breite = 4;
const laenge = 5.5;

console.log("Fläche:", breite * laenge);
console.log("Umfang:", 2 * breite + 2 * laenge);

console.log();

// Eine kleine Überraschung
console.log(0.1 + 0.2);

console.log();

// Besondere Zahlenwerte
console.log(10 / 0);
console.log(-10 / 0);
console.log("Hallo" * 3);
