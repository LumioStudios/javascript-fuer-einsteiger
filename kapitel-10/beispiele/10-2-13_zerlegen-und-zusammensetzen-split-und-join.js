// Kapitel 10.2: Wichtige String-Methoden
// Zerlegen und zusammensetzen: split und join
// Ausführen im Ordner kapitel-10: node beispiele/10-2-13_zerlegen-und-zusammensetzen-split-und-join.js

const woerter = ["Das", "ist", "toll"];

console.log(woerter.join(" "));
console.log(woerter.join("-"));
console.log(woerter.join(""));

// Ausgabe:
// Das ist toll
// Das-ist-toll
// Dasisttoll
