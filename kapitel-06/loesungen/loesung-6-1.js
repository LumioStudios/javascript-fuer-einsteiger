// Lösung zu Übung 6.1 – Zählen mit for

// Teil 1: Zahlen von 1 bis 10
for (let i = 1; i <= 10; i++) {
  console.log(i);
}

// Teil 2: Countdown von 10 bis 0
for (let sekunde = 10; sekunde >= 0; sekunde--) {
  console.log(sekunde);
}

console.log("Abheben!");

// Teil 3: Fünferschritte von 5 bis 50
for (let zahl = 5; zahl <= 50; zahl += 5) {
  console.log(zahl);
}
