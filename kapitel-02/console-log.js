// Abschnitt 2.3: Ausgaben mit console.log

// Texte ausgeben
console.log("Guten Morgen!");
console.log("JavaScript macht Spaß.");

// Zahlen ausgeben
console.log(42);
console.log(3.14);
console.log(-7);

// Rechnen in der Ausgabe
console.log(5 + 3);
console.log(10 - 4);
console.log(6 * 7);
console.log(20 / 4);

// Rechnung oder Text?
console.log(5 + 3);
console.log("5 + 3");

// Mehrere Werte auf einmal
console.log("Ergebnis:", 5 + 3);
console.log("Ein Jahr hat", 365, "Tage.");

// Eine leere Zeile
console.log("Teil 1");
console.log();
console.log("Teil 2");
